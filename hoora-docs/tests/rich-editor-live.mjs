import { chromium } from 'playwright';
import { loadEnvFile } from 'node:process';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
loadEnvFile();
const credentials=JSON.parse(await readFile('.credentials.admin.json','utf8'));
const auth=await fetch(process.env.SUPABASE_URL+'/auth/v1/token?grant_type=password',{method:'POST',headers:{apikey:process.env.SUPABASE_ANON_KEY,'Content-Type':'application/json'},body:JSON.stringify(credentials)});
if(!auth.ok)throw new Error('Test administrator login failed');
const session=await auth.json();
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1360,height:900}});
await context.addInitScript(s=>localStorage.setItem('hoora-session',JSON.stringify({...s,expires_at:Date.now()/1000+s.expires_in})),session);
const page=await context.newPage(),errors=[];
page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto('http://127.0.0.1:3001/#/new');
 await page.locator('.rich-content[contenteditable="true"]').waitFor({timeout:15000});
 await page.locator('[data-editor-view="source"]').click();
 await page.locator('#body').fill('## A formatted heading\n\nA **bold** detail and *italic* detail.\n\n| What | Result |\n|---|---|\n| Source | Preview |');
 await page.locator('[data-editor-view="write"]').click();
 assert.equal(await page.locator('.rich-content h2').innerText(),'A formatted heading');
 assert.equal(await page.locator('.rich-content strong').innerText(),'bold');
 assert.equal(await page.locator('.rich-content table').count(),1);
 await page.locator('[data-editor-view="split"]').click();
 assert.equal(await page.locator('#live-preview table').count(),1);
 await page.locator('.rich-content p').first().click();
 await page.locator('[data-rich-command="bulletList"]').click();
 assert.equal(await page.locator('.rich-content ul').count(),1);
 await page.goto('http://127.0.0.1:3001/#/releases?version=5.11.0');
 await page.locator('.application-release').first().waitFor();
 await page.getByRole('button',{name:'Add my notes',exact:true}).first().click();
 await page.locator('#entry-body').waitFor({state:'attached'});
 await page.locator('[data-entry-view="source"]').click();
 await page.locator('#entry-body').fill('### Contributed heading\n\n**My note**');
 await page.locator('[data-entry-view="visual"]').click();
 assert.equal(await page.locator('.entry-writing .rich-content h3').innerText(),'Contributed heading');
 assert.equal(await page.locator('.entry-writing .rich-content strong').innerText(),'My note');
 await page.locator('[data-entry-view="preview"]').click();
 assert.match(await page.locator('#entry-preview').innerText(),/My note/);
 assert.deepEqual(errors,[]);
 console.log('Rich editor passed: source Markdown, visual formatting, table, list, split preview and contribution modal. No content was saved.');
}finally{await browser.close()}
