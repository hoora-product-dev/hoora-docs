const cache = new Map();
export function icon(name) {
  if (cache.has(name)) return cache.get(name);
  let svg;
  if (name === 'microsoft')
    svg =
      '<svg viewBox="0 0 24 24" fill="currentColor" aria-hidden="true"><path d="M2 2h9v9H2zM13 2h9v9h-9zM2 13h9v9H2zM13 13h9v9h-9z"/></svg>';
  else
    svg = createElement(nodes[name] || FileText, {
      width: 20,
      height: 20,
      'stroke-width': 1.75,
      'aria-hidden': 'true',
      focusable: 'false',
    }).outerHTML;
  const markup = `<span class="icon">${svg}</span>`;
  cache.set(name, markup);
  return markup;
}
