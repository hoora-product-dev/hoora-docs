begin;

-- Tables created through a direct Postgres connection do not inherit the
-- dashboard's API grants. Server routes use the secret API key, which maps to
-- service_role, for verified provisioning and administrative operations.
grant usage on schema public to service_role;
grant all privileges on all tables in schema public to service_role;
grant all privileges on all sequences in schema public to service_role;
grant execute on all functions in schema public to service_role;

alter default privileges for role postgres in schema public
  grant all privileges on tables to service_role;
alter default privileges for role postgres in schema public
  grant all privileges on sequences to service_role;
alter default privileges for role postgres in schema public
  grant execute on functions to service_role;

commit;
